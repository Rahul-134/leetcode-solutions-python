class Solution:
    def countCommas(self, n: int) -> int:
        if n < 1000:
            return 0
        c1, c2, c3, c4, c5 = 0, 0, 0, 0, 0
        if 1000 <= n < 1000000:
            c1 += n-999
        elif 1000000 <= n < 1000000000:
            c1 = 999000
            c2 += n-999999
        elif 1000000000 <= n < 1000000000000:
            c1 = 999000
            c2 = 999000000
            c3 += n-999999999
        elif 1000000000000 <= n < 1000000000000000:
            c1 = 999000
            c2 = 999000000
            c3 = 999000000000
            c4 += n-999999999999
        elif n>=1000000000000000:
            c1 = 999000
            c2 = 999000000
            c3 = 999000000000
            c4 = 999000000000000
            c5 += n-999999999999999
        return c1 + c2*2 + c3*3 + c4*4 + c5*5

